package sync

import (
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"ai-specs.dev/worktree-gate/shared"
)

const hooksManagedPrefix = "ai-specs:hooks:"
const hooksTSHeader = "// GENERATED by ai-specs — do not edit.\n// Runtime hook "
const hooksCursorHeader = "#!/usr/bin/env bash\n# GENERATED by ai-specs — do not edit. Runs the recipe hook script and\n"

// Prune all runtimes, including ones not selected for this fan-out. Absence
// of an agent alone is not a reason to remove its otherwise current wiring.
func pruneRuntimeHooks(root string, hooks []any) error {
	for _, target := range []struct{ agent, json, dir, ext, header string }{
		{"claude", ".claude/settings.json", "", "", ""},
		{"cursor", ".cursor/hooks.json", ".cursor/hooks", ".sh", hooksCursorHeader},
		{"opencode", "", ".opencode/plugin", ".ts", hooksTSHeader},
		{"pi", "", ".pi/extensions", ".ts", hooksTSHeader},
		{"omp", "", ".omp/extensions", ".ts", hooksTSHeader},
	} {
		ids, shims := map[string]string{}, map[string]string{}
		for _, raw := range hooks {
			h, _ := raw.(*mcpObj)
			event, _ := hooksGet(h, "event").(string)
			native, ok := hooksEventMap[event][target.agent].(string)
			if !ok {
				continue
			}
			if target.agent == "cursor" && event == "pre-tool-use" {
				if skip, err := hooksMatcherTargetsFileWrites(hooksGet(h, "matcher")); skip || err != nil {
					continue
				}
			}
			id, _ := hooksManagedID(h)
			base, _ := hooksShimBasename(h)
			ids[id], shims[base+target.ext] = native, event
		}
		if err := pruneHookBuckets(root, target.json, ids); err != nil {
			return err
		}
		if err := pruneHookShims(root, target.dir, target.ext, target.header, shims); err != nil {
			return err
		}
	}
	return nil
}

func pruneHookBuckets(root, rel string, ids map[string]string) error {
	path := filepath.Join(root, rel)
	if info, err := os.Lstat(path); rel == "" || err != nil || !info.Mode().IsRegular() {
		return nil
	}
	if err := shared.EnsureTemplateAncestorsReal(root, path); err != nil {
		return err
	}
	doc, err := hooksLoadJSONFile(path)
	if err != nil { // Invalid JSON recovery belongs to the renderer.
		return nil
	}
	hooks := hooksObjOrNew(doc, "hooks")
	changed := false
	for _, event := range hooks.keys {
		bucket := mcpAsList(hooks.vals[event])
		keep := slices.DeleteFunc(bucket, func(raw any) bool {
			entry, _ := raw.(*mcpObj)
			id, _ := hooksGet(entry, hooksManagedKey).(string)
			native, live := ids[id]
			return strings.HasPrefix(id, hooksManagedPrefix) && (!live || native != event)
		})
		if len(keep) != len(bucket) {
			hooks.set(event, keep)
			changed = true
		}
	}
	if changed {
		return hooksWriteJSONFile(path, doc)
	}
	return nil
}

func pruneHookShims(root, dir, ext, header string, live map[string]string) error {
	if dir == "" {
		return nil
	}
	path := filepath.Join(root, dir)
	if err := shared.EnsureTemplateAncestorsReal(root, filepath.Join(path, "shim")); err != nil {
		return err
	}
	entries, err := os.ReadDir(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, entry := range entries {
		name := entry.Name()
		if !entry.Type().IsRegular() || filepath.Ext(name) != ext {
			continue
		}
		if event := live[name]; event != "" && ext == ".sh" {
			continue // A Cursor wrapper does not embed the native event.
		}
		file := filepath.Join(path, name)
		f, err := os.Open(file)
		if err != nil {
			return err
		}
		prefix, err := io.ReadAll(io.LimitReader(f, 512))
		_ = f.Close()
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(prefix), header) {
			continue // A matching basename alone does not establish ownership.
		}
		if event := live[name]; event == "" || !strings.Contains(string(prefix), " (event "+event+").\n") {
			if err := os.Remove(file); err != nil {
				return err
			}
		}
	}
	return nil
}
