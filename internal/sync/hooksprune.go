const hooksManagedPrefix = "ai-specs:hooks:"
const hooksTSHeader = "// GENERATED by ai-specs — do not edit.\n// Runtime hook "
const hooksCursorHeader = "#!/usr/bin/env bash\n# GENERATED by ai-specs — do not edit. Runs the recipe hook script and\n"

// loadPruneInputs reads just the hook identity needed before materialization.
// Merged configuration changes hook content, not its path, event or matcher.
func loadPruneInputs(root, home string) ([]string, []any, error) {
	manifest, err := loadMaterializeManifest(materializeManifestPath(root))
	if err != nil {
		return nil, nil, err
	}
	var enabled []string
	var hooks []any
	for _, entry := range loadMaterializeRecipes(manifest) {
		if !entry.Enabled {
			continue
		}
		recipe, err := schema.LoadRecipeToml(filepath.Join(home, "catalog", "recipes", entry.ID, "recipe.toml"))
		if err != nil {
			return nil, nil, err
		}
		enabled = append(enabled, entry.ID)
		for _, hook := range recipe.RuntimeHooks {
			rel := shared.HookScriptRelPath(entry.ID, hook.Script)
			hooks = append(hooks, materializeResolvedHookEntry(entry.ID, hook, rel, nil))
		}
	}
	return enabled, hooks, nil
}

// pruneFile accepts an absent leaf, but never follows a symlink or treats a
// directory (even an empty one) as an owned file.
func pruneFile(root, path string) (bool, error) {
	if err := shared.EnsureTemplateAncestorsReal(root, path); err != nil {
		return false, err
	}
	info, err := os.Lstat(path)
	switch {
	case os.IsNotExist(err):
		return false, nil
	case err != nil:
		return false, err
	case info.Mode()&os.ModeSymlink != 0:
		return false, fmt.Errorf("%w: %s", shared.ErrDestSymlink, path)
	case info.IsDir():
		return false, fmt.Errorf("destination is a directory: %s", path)
	case !info.Mode().IsRegular():
		return false, fmt.Errorf("destination is not a regular file: %s", path)
	}
	return true, nil
}

// Plan all runtimes, including ones not selected for this fan-out. Absence
// of an agent alone is not a reason to remove its otherwise current wiring.
func planRuntimeHookPrune(projectRoot, root string, hooks []any) (func() error, error) {
	var apply []func() error
	for _, target := range []struct{ agent, json, dir, ext, header string }{
		{"claude", ".claude/settings.json", "", "", ""},
		{"cursor", ".cursor/hooks.json", ".cursor/hooks", ".sh", hooksCursorHeader},
		{"opencode", "", ".opencode/plugin", ".ts", hooksTSHeader},
		{"pi", "", ".pi/extensions", ".ts", hooksTSHeader},
		{"omp", "", ".omp/extensions", ".ts", hooksTSHeader},
	} {
		ids, shims := map[string]string{}, map[string]string{}
		for _, raw := range hooks {
			h, _ := raw.(*mcpObj)
			event, _ := hooksGet(h, "event").(string)
			native, ok := hooksEventMap[event][target.agent].(string)
			if !ok {
				continue
			}
			if target.agent == "cursor" && event == "pre-tool-use" {
				if skip, err := hooksMatcherTargetsFileWrites(hooksGet(h, "matcher")); skip || err != nil {
					continue
				}
			}
			id, _ := hooksManagedID(h)
			base, _ := hooksShimBasename(h)
			ids[id], shims[base+target.ext] = native, event
		}
		write, err := planHookBucketPrune(root, target.json, ids)
		if err != nil {
			return nil, err
		}
		if write != nil {
			apply = append(apply, write)
		}
		files, err := planHookShimPrune(root, target.dir, target.ext, target.header, shims)
		if err != nil {
			return nil, err
		}
		if len(files) > 0 {
			apply = append(apply, func() error { return applyHookShimPrune(projectRoot, root, files) })
		}
	}
	return func() error {
		for _, op := range apply {
			if err := op(); err != nil {
				return err
			}
		}
		return nil
	}, nil
}

func planHookBucketPrune(root, rel string, ids map[string]string) (func() error, error) {
	if rel == "" {
		return nil, nil
	}
	path := filepath.Join(root, rel)
	if _, err := pruneFile(root, path); err != nil {
		return nil, err
	}
	return func() error { return applyHookBucketPrune(root, path, ids) }, nil
}

func applyHookBucketPrune(root, path string, ids map[string]string) error {
	if exists, err := pruneFile(root, path); err != nil || !exists {
		return err
	}
	// Materialization may have replaced this JSON file since preflight.
	doc, err := hooksLoadJSONFile(path)
	if err != nil { // Invalid JSON recovery belongs to the renderer.
		return nil
	}
	hooks := hooksObjOrNew(doc, "hooks")
	changed := false
	for _, event := range hooks.keys {
		bucket := mcpAsList(hooks.vals[event])
		keep := slices.DeleteFunc(bucket, func(raw any) bool {
			entry, _ := raw.(*mcpObj)
			id, _ := hooksGet(entry, hooksManagedKey).(string)
			native, live := ids[id]
			return strings.HasPrefix(id, hooksManagedPrefix) && (!live || native != event)
		})
		if len(keep) != len(bucket) {
			hooks.set(event, keep)
			changed = true
		}
	}
	if changed {
		return hooksWriteJSONFile(path, doc)
	}
	return nil
}

type hookShimPrune struct{ path, hash string }

func planHookShimPrune(root, dir, ext, header string, live map[string]string) ([]hookShimPrune, error) {
	if dir == "" {
		return nil, nil
	}
	path := filepath.Join(root, dir)
	if err := shared.EnsureTemplateAncestorsReal(root, filepath.Join(path, "shim")); err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(path)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var doomed []hookShimPrune
	for _, entry := range entries {
		name := entry.Name()
		if !entry.Type().IsRegular() || filepath.Ext(name) != ext {
			continue
		}
		if event := live[name]; event != "" && ext == ".sh" {
			continue // A Cursor wrapper does not embed the native event.
		}
		file := filepath.Join(path, name)
		f, err := os.Open(file)
		if err != nil {
			return nil, err
		}
		prefix, err := io.ReadAll(io.LimitReader(f, 512))
		_ = f.Close()
		if err != nil {
			return nil, err
		}
		if !strings.HasPrefix(string(prefix), header) {
			continue // A matching basename alone does not establish ownership.
		}
		if event := live[name]; event == "" || !strings.Contains(string(prefix), " (event "+event+").\n") {
			if exists, err := pruneFile(root, file); err != nil {
				return nil, err
			} else if exists {
				hash, err := lock.Sha256OfFile(file)
				if err != nil {
					return nil, err
				}
				doomed = append(doomed, hookShimPrune{file, hash})
			}
		}
	}
	return doomed, nil
}

func applyHookShimPrune(projectRoot, root string, doomed []hookShimPrune) error {
	// Materialization records template ownership in the project root lock,
	// including templates whose destinations are inside a fan-out target.
	lk, err := lock.LoadLock(filepath.Join(projectRoot, bundledLockRel))
	if err != nil {
		return err
	}
	for _, shim := range doomed {
		rel, err := filepath.Rel(projectRoot, shim.path)
		if err != nil {
			return err
		}
		if lk.Managed[filepath.ToSlash(rel)] != nil {
			continue
		}
		exists, err := pruneFile(root, shim.path)
		if err != nil {
			return err
		}
		if !exists {
			continue
		}
		hash, err := lock.Sha256OfFile(shim.path)
		if err != nil {
			return err
		}
		if hash == shim.hash {
			if err := os.Remove(shim.path); err != nil {
				return err
			}
		}
	}
	return nil
}
