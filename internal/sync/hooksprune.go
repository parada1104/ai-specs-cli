const hooksManagedPrefix = "ai-specs:hooks:"
const hooksTSHeader = "// GENERATED by ai-specs — do not edit.\n// Runtime hook "
const hooksCursorHeader = "#!/usr/bin/env bash\n# GENERATED by ai-specs — do not edit. Runs the recipe hook script and\n"

// loadPruneInputs reads artifact identities before materialization, independent of merged config.
func loadPruneInputs(root, home string) ([]string, []any, map[string]string, error) {
	manifest, err := loadMaterializeManifest(materializeManifestPath(root))
	if err != nil {
		return nil, nil, nil, err
	}
	var enabled []string
	var hooks []any
	commands := map[string]string{}
	for _, entry := range loadMaterializeRecipes(manifest) {
		if !entry.Enabled {
			continue
		}
		recipe, err := schema.LoadRecipeToml(filepath.Join(home, "catalog", "recipes", entry.ID, "recipe.toml"))
		if err != nil {
			return nil, nil, nil, err
		}
		enabled = append(enabled, entry.ID)
		for _, command := range recipe.Commands {
			commands[command.ID+".md"] = entry.ID
		}
		for _, hook := range recipe.RuntimeHooks {
			rel := shared.HookScriptRelPath(entry.ID, hook.Script)
			hooks = append(hooks, materializeResolvedHookEntry(entry.ID, hook, rel, nil))
		}
	}
	return enabled, hooks, commands, nil
}

// pruneFile accepts an absent leaf, but never follows a symlink or treats a
// directory (even an empty one) as an owned file. The ancestor guard keeps the
// strict rule: this primitive is shared with the command/template guards.
func pruneFile(root, path string) (bool, error) {
	if err := shared.EnsureTemplateAncestorsReal(root, path); err != nil {
		return false, err
	}
	return pruneFileLeaf(path)
}

// pruneHookFile is pruneFile for the runtime-hook plan: the ancestor guard uses
// the project's inside-root rule (T6b) — a symlinked ancestor that fully
// resolves inside the main project root is allowed, since a deletion through it
// still stays inside the project; outside, chained-outside and dangling links
// are still refused. One rule, one helper: symlinkedAncestorOutside.
func pruneHookFile(projectRoot, root, path string) (bool, error) {
	if ancestor, bad := symlinkedAncestorOutside(projectRoot, root, path); bad {
		return false, fmt.Errorf("%w: %s", shared.ErrAncestorSymlink, ancestor)
	}
	return pruneFileLeaf(path)
}

// pruneFileLeaf is the leaf half of pruneFile: absent, symlink, directory and
// non-regular-file outcomes.
func pruneFileLeaf(path string) (bool, error) {
	info, err := os.Lstat(path)
	switch {
	case os.IsNotExist(err):
		return false, nil
	case err != nil:
		return false, err
	case info.Mode()&os.ModeSymlink != 0:
		return false, fmt.Errorf("%w: %s", shared.ErrDestSymlink, path)
	case info.IsDir():
		return false, fmt.Errorf("destination is a directory: %s", path)
	case !info.Mode().IsRegular():
		return false, fmt.Errorf("destination is not a regular file: %s", path)
	}
	return true, nil
}

// Plan all runtimes, including ones not selected for this fan-out. Absence
// of an agent alone is not a reason to remove its otherwise current wiring.
func planRuntimeHookPrune(projectRoot, root string, hooks []any) (func(io.Writer) error, error) {
	records := map[string]string{}
	if lk, err := lock.LoadLock(filepath.Join(projectRoot, bundledLockRel)); err != nil {
		return nil, err
	} else if lk != nil {
		records = lk.Hooks
	}
	var apply []func(io.Writer) error
	var legacy []string
	// Dropping a record only removes deletion authority, so every record whose
	// shim is gone loses it — even for a target this sync never visits (an
	// omitted subrepo, a removed agent).
	apply = append(apply, func(io.Writer) error {
		return applyHookShimRecordSweep(projectRoot, absentHookShims(projectRoot, records))
	})
	for _, target := range []struct{ agent, json, dir, ext, header string }{
		{"claude", ".claude/settings.json", "", "", ""},
		{"cursor", ".cursor/hooks.json", ".cursor/hooks", ".sh", hooksCursorHeader},
		{"opencode", "", ".opencode/plugin", ".ts", hooksTSHeader},
		{"pi", "", ".pi/extensions", ".ts", hooksTSHeader},
		{"omp", "", ".omp/extensions", ".ts", hooksTSHeader},
	} {
		ids, shims := map[string]string{}, map[string]hookShimLive{}
		for _, raw := range hooks {
			h, _ := raw.(*mcpObj)
			event, _ := hooksGet(h, "event").(string)
			native, ok := hooksEventMap[event][target.agent].(string)
			if !ok {
				continue
			}
			if target.agent == "cursor" && event == "pre-tool-use" {
				if skip, err := hooksMatcherTargetsFileWrites(hooksGet(h, "matcher")); skip || err != nil {
					continue
				}
			}
			id, _ := hooksManagedID(h)
			base, _ := hooksShimBasename(h)
			ids[id], shims[base+target.ext] = native, hookShimLive{owner: id, event: event}
		}
		write, err := planHookBucketPrune(projectRoot, root, target.json, ids)
		if err != nil {
			return nil, err
		}
		if write != nil {
			apply = append(apply, write)
		}
		plan, err := planHookShimPrune(projectRoot, root, target.dir, target.ext, target.header, shims, records)
		if err != nil {
			return nil, err
		}
		legacy = append(legacy, plan.legacy...)
		if len(plan.doomed) > 0 {
			planned := plan
			apply = append(apply, func(io.Writer) error { return applyHookShimPrune(projectRoot, root, planned) })
		}
	}
	return func(stderr io.Writer) error {
		if len(legacy) > 0 {
			fmt.Fprintf(stderr, "  ! %s: generated hook shims not recorded as ai-specs-managed (kept; delete them if ai-specs did not write them)\n", strings.Join(legacy, ", "))
		}
		for _, op := range apply {
			if err := op(stderr); err != nil {
				return err
			}
		}
		return nil
	}, nil
}

func planHookBucketPrune(projectRoot, root, rel string, ids map[string]string) (func(io.Writer) error, error) {
	if rel == "" {
		return nil, nil
	}
	path := filepath.Join(root, rel)
	if _, err := pruneHookFile(projectRoot, root, path); err != nil {
		return nil, err
	}
	return func(stderr io.Writer) error { return applyHookBucketPrune(projectRoot, root, path, ids, stderr) }, nil
}

func applyHookBucketPrune(projectRoot, root, path string, ids map[string]string, stderr io.Writer) error {
	if exists, err := pruneHookFile(projectRoot, root, path); err != nil || !exists {
		return err
	}
	// Materialization may have replaced this JSON file since preflight.
	doc, invalid, err := loadJSONTarget(path)
	if err != nil {
		return err
	}
	hooks := hooksObjOrNew(doc, "hooks")
	changed := invalid != nil
	for _, event := range hooks.keys {
		bucket := mcpAsList(hooks.vals[event])
		keep := slices.DeleteFunc(bucket, func(raw any) bool {
			entry, _ := raw.(*mcpObj)
			id, _ := hooksGet(entry, hooksManagedKey).(string)
			native, live := ids[id]
			return strings.HasPrefix(id, hooksManagedPrefix) && (!live || native != event)
		})
		if len(keep) != len(bucket) {
			hooks.set(event, keep)
			changed = true
		}
	}
	if changed {
		if err := backupInvalidJSON(projectRoot, path, invalid, stderr); err != nil {
			return err
		}
		return hooksWriteJSONFile(projectRoot, path, doc)
	}
	return nil
}

// hookShimLive is the wiring a hook still declares for one agent: the managed
// id that owns the shim and the abstract event it is wired for.
type hookShimLive struct{ owner, event string }

// hookShimPlan is the preflight of one agent's shim directory.
type hookShimPlan struct {
	// doomed shims are recorded as owned by a hook that no longer produces
	// them; they are deleted even when edited or stripped of the marker.
	doomed []hookShimPrune
	// legacy shims look generated but have no ownership record: kept, warned.
	legacy []string
}

type hookShimPrune struct{ path, owner string }

// planHookShimPrune decides by the lock's ownership record, never by the
// generated marker alone: a recorded path whose owner is gone is pruned, an
// unrecorded one is kept with one notice.
func planHookShimPrune(projectRoot, root, dir, ext, header string, live map[string]hookShimLive, records map[string]string) (hookShimPlan, error) {
	var plan hookShimPlan
	if dir == "" {
		return plan, nil
	}
	path := filepath.Join(root, dir)
	if ancestor, bad := symlinkedAncestorOutside(projectRoot, root, filepath.Join(path, "shim")); bad {
		return plan, fmt.Errorf("%w: %s", shared.ErrAncestorSymlink, ancestor)
	}
	entries, err := os.ReadDir(path)
	if err == nil {
		for _, entry := range entries {
			name := entry.Name()
			if !entry.Type().IsRegular() || filepath.Ext(name) != ext {
				continue
			}
			file := filepath.Join(path, name)
			rel, relErr := filepath.Rel(projectRoot, file)
			if relErr != nil {
				continue
			}
			rel = filepath.ToSlash(rel)
			wiring, isLive := live[name]
			recorded, hasRecord := records[rel]
			switch {
			case hasRecord && recorded == wiring.owner:
				continue // current wiring; the renderer refreshes the event
			case hasRecord && isLive:
				continue // another live hook now writes this path; never delete it
			case hasRecord:
				if exists, err := pruneHookFile(projectRoot, root, file); err != nil {
					return plan, err
				} else if exists {
					plan.doomed = append(plan.doomed, hookShimPrune{file, recorded})
				}
			case isLive:
				continue
			default:
				// The marker alone proves generation, not ownership.
				if prefix, err := readFilePrefix(file, 512); err == nil && strings.HasPrefix(prefix, header) {
					plan.legacy = append(plan.legacy, rel)
				}
			}
		}
	} else if !os.IsNotExist(err) {
		return plan, err
	}
	return plan, nil
}

// absentHookShims lists the records whose shim no longer exists, keyed from the
// project root so a target's location relative to the lock never matters.
func absentHookShims(projectRoot string, records map[string]string) []string {
	var absent []string
	for _, rel := range sortedKeys(records) {
		if !fs.ValidPath(rel) || strings.Contains(rel, `\`) {
			continue
		}
		if _, err := os.Lstat(filepath.Join(projectRoot, filepath.FromSlash(rel))); os.IsNotExist(err) {
			absent = append(absent, rel)
		}
	}
	return absent
}

// applyHookShimRecordSweep drops records whose shim is still absent; a shim
// that reappeared since preflight keeps its record.
func applyHookShimRecordSweep(projectRoot string, absent []string) error {
	if len(absent) == 0 {
		return nil
	}
	lockPath := filepath.Join(projectRoot, bundledLockRel)
	lk, err := lock.LoadLock(lockPath)
	if err != nil {
		return err
	}
	changed := false
	for _, rel := range absent {
		if lk.Hooks[rel] == "" {
			continue
		}
		if _, err := os.Lstat(filepath.Join(projectRoot, filepath.FromSlash(rel))); !os.IsNotExist(err) {
			continue
		}
		delete(lk.Hooks, rel)
		changed = true
	}
	if !changed {
		return nil
	}
	return lock.WriteLock(lockPath, lk)
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func readFilePrefix(path string, limit int64) (string, error) {
	f, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer f.Close()
	prefix, err := io.ReadAll(io.LimitReader(f, limit))
	return string(prefix), err
}

func applyHookShimPrune(projectRoot, root string, plan hookShimPlan) error {
	// Materialization records template ownership in the project root lock,
	// including templates whose destinations are inside a fan-out target.
	lockPath := filepath.Join(projectRoot, bundledLockRel)
	lk, err := lock.LoadLock(lockPath)
	if err != nil {
		return err
	}
	changed := false
	for _, shim := range plan.doomed {
		rel, err := filepath.Rel(projectRoot, shim.path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if lk.Managed[rel] != nil || lk.Hooks[rel] != shim.owner {
			continue // The destination was repurposed since preflight.
		}
		exists, err := pruneHookFile(projectRoot, root, shim.path)
		if err != nil {
			return err
		}
		if exists {
			if err := os.Remove(shim.path); err != nil {
				return err
			}
		}
		delete(lk.Hooks, rel)
		changed = true
	}
	if changed {
		return lock.WriteLock(lockPath, lk)
	}
	return nil
}
