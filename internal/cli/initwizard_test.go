// TestInitWizardNeverOverwritesAnExistingManifest pins S16's last sentence and
// S4: a manifest already at the real path survives a confirmed wizard byte for
// byte — only the staged copy carries the new choices.
func TestInitWizardNeverOverwritesAnExistingManifest(t *testing.T) {
	f := newWizardFixture(t)
	f.seedRecipe(t, "foo.bar", wizardRecipeBody("foo.bar", "1.2.3", "dotted recipe"))
	realPath := filepath.Join(f.target, "ai-specs", "ai-specs.toml")
	if err := os.MkdirAll(filepath.Dir(realPath), 0o755); err != nil {
		t.Fatal(err)
	}
	user := []byte("# hand-edited\nname = \"keepme\"\n")
	if err := os.WriteFile(realPath, user, 0o644); err != nil {
		t.Fatal(err)
	}

	res, rc := runInitWizard(f.request(wizardScript(
		enterText(), tui.KeyEnter, tui.KeyEnter, tui.KeySpace, tui.KeyEnter, tui.KeyEnter,
	)))
	if rc != 0 {
		t.Fatalf("exit = %d, want 0; stderr=%q", rc, f.stderr.String())
	}
	if got := readFile(t, realPath); got != string(user) {
		t.Errorf("the user's manifest was overwritten:\n%s", got)
	}
	if staged := readFile(t, res.Staged); staged == string(user) {
		t.Error("the staged manifest equals the user's bytes: the wizard did not render its own")
	}
}

// TestRenderWizardManifest pins S16's render rules the flow cannot reach yet:
// the config table (S16), project-owned keys never under a recipe (S18), bare
// versus quoted keys (S17) and the no-recipes shape.
func TestRenderWizardManifest(t *testing.T) {
	t.Parallel()
	configured := map[string]map[string]any{
		"cfg-one":  {"gate_mode": "always", "auto_remove_merged": true, "a.b": "x"},
		"topo-own": {"repo_topology": "standalone", "gate_mode": "ask"},
	}
	text, err := renderWizardManifest("demo", []string{"claude"}, []string{"cfg-one", "topo-own"}, configured, "monorepo-submodules")
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	for _, want := range []string{
		"repo_topology = \"monorepo-submodules\"",
		"[recipes.cfg-one.config]",
		`"a.b" = "x"`,
		"auto_remove_merged = true",
		`gate_mode = "always"`,
		"[recipes.topo-own.config]",
		`gate_mode = "ask"`,
	} {
		if !strings.Contains(text, want) {
			t.Errorf("render lacks %q:\n%s", want, text)
		}
	}
	// Config keys are sorted: "a.b" before "auto_remove_merged".
	if strings.Index(text, `"a.b"`) > strings.Index(text, "auto_remove_merged") {
		t.Errorf("config keys are not sorted:\n%s", text)
	}
	// S18: repo_topology is project-owned — exactly one occurrence, under [project].
	if n := strings.Count(text, "repo_topology"); n != 1 {
		t.Errorf("repo_topology appears %d times, want 1 (project-owned):\n%s", n, text)
	}
	if strings.Contains(text, "recipes.topo-own.config]\nrepo_topology") {
		t.Errorf("repo_topology was written under a recipe config:\n%s", text)
	}

	// S17: dotted ids quoted, bare ids bare.
	withIDs, err := renderWizardManifest("demo", []string{"claude"}, []string{"plain-id", "foo.bar"}, nil, "auto")
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if !strings.Contains(withIDs, "[recipes.plain-id]") || !strings.Contains(withIDs, `[recipes."foo.bar"]`) {
		t.Errorf("key quoting wrong:\n%s", withIDs)
	}

	// No recipes: no recipes section at all, just the trailing comment pair.
	// (The header COMMENT mentions [recipes.<id>], so the check is for a
	// recipes TABLE at the start of a line.)
	bare, err := renderWizardManifest("demo", []string{"claude"}, nil, nil, "auto")
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if strings.Contains(bare, "# Recipes") || strings.Contains(bare, "\n[recipes.") {
		t.Errorf("an empty selection rendered a recipes section:\n%s", bare)
	}
	if !strings.Contains(bare, "# [[deps]] — add with: ai-specs skills add <url>\n# [mcp.*]") {
		t.Errorf("the trailing comment pair is missing:\n%s", bare)
	}
}

