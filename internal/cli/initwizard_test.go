// scriptedWizardKeys feeds the wizard's two seams: list/confirm prompts read
// keys, the name prompt reads text events. Exhausting either is EOF, which is
// the wizard's cancel path.
type scriptedWizardKeys struct {
	keys   []tui.Key
	keyAt  int
	text   []tui.TextKey
	textAt int
}

func (s *scriptedWizardKeys) NextKey() (tui.Key, error) {
	if s.keyAt >= len(s.keys) {
		return 0, io.EOF
	}
	k := s.keys[s.keyAt]
	s.keyAt++
	return k, nil
}

func (s *scriptedWizardKeys) NextTextKey() (tui.TextKey, error) {
	if s.textAt >= len(s.text) {
		return tui.TextKey{}, io.EOF
	}
	e := s.text[s.textAt]
	s.textAt++
	return e, nil
}

func enterText() []tui.TextKey { return []tui.TextKey{{Kind: tui.TextEnter}} }

func wizardScript(text []tui.TextKey, keys ...tui.Key) *scriptedWizardKeys {
	return &scriptedWizardKeys{text: text, keys: keys}
}

type wizardFixture struct {
	target string
	home   string
	tmp    string
	stdout bytes.Buffer
	stderr bytes.Buffer
}

// newWizardFixture builds an isolated target + CLI home and points TMPDIR at a
// private directory, so the staging files the wizard creates are countable.
func newWizardFixture(t *testing.T) *wizardFixture {
	t.Helper()
	root := t.TempDir()
	f := &wizardFixture{
		target: filepath.Join(root, "proj"),
		home:   filepath.Join(root, "home"),
		tmp:    filepath.Join(root, "tmp"),
	}
	for _, dir := range []string{f.target, f.home, f.tmp} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("TMPDIR", f.tmp)
	return f
}

// request builds the wizard request with a scripted key source standing in for
// the production raw-mode terminal.
func (f *wizardFixture) request(keys *scriptedWizardKeys) initWizardRequest {
	return initWizardRequest{
		Target: f.target,
		Name:   "demo",
		Home:   f.home,
		Stdin:  strings.NewReader(""),
		Stdout: &f.stdout,
		Stderr: &f.stderr,
		OpenKeys: func(io.Reader, io.Writer) (tui.KeySource, func(), int) {
			return keys, func() {}, 0
		},
	}
}

func (f *wizardFixture) seedRecipe(t *testing.T, dir, body string) {
	t.Helper()
	path := filepath.Join(f.home, "catalog", "recipes", dir)
	if err := os.MkdirAll(path, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(path, "recipe.toml"), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func (f *wizardFixture) stagingEntries(t *testing.T) []string {
	t.Helper()
	entries, err := os.ReadDir(f.tmp)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), "ai-specs-init-tui-") {
			names = append(names, e.Name())
		}
	}
	return names
}

func (f *wizardFixture) assertNoProjectWrites(t *testing.T) {
	t.Helper()
	if _, err := os.Stat(filepath.Join(f.target, "ai-specs")); !os.IsNotExist(err) {
		t.Errorf("the wizard wrote %s/ (stat err=%v), want no project files", filepath.Join(f.target, "ai-specs"), err)
	}
	if got := f.stagingEntries(t); len(got) != 0 {
		t.Errorf("staging files left behind: %v", got)
	}
}

// wizardRecipeBody builds a minimal catalog recipe.toml whose [recipe] id
// matches its directory, which is the shape every picker assertion below
// depends on.
func wizardRecipeBody(id, version, description string) string {
	return fmt.Sprintf("[recipe]\nid = %q\nname = %q\ndescription = %q\nversion = %q\n",
		id, id, description, version)
}

// wantStagedManifest is init_tui.py `_render_manifest`'s output for the full
// flow below, byte for byte (S16): header, [project], [agents], one
// [recipes.<id>] table with the dotted key quoted (S17), trailing comments.
const wantStagedManifest = `# ai-specs.toml — project root manifest (generated by ai-specs init --tui).
#
# Canonical surface: [project], [agents], [recipes.<id>], [[deps]],
# [[bindings]], [mcp.<name>], [brief]. See docs/ai-specs-toml.md.
#
# Local skills under ai-specs/skills/<name>/ are autodiscovered.

[project]
name = "demo"
subrepos = []
repo_topology = "auto"

[agents]
enabled = ["claude", "cursor", "opencode"]

# Recipes — named bundles from catalog/recipes/<id>/
[recipes."foo.bar"]
enabled = true

# [[deps]] — add with: ai-specs skills add <url>
# [mcp.*]  — optional MCP servers; distributed by sync-agent
`

// wantStagedSidecar is `json.dumps(meta) + "\n"` with its insertion order and
// ", " / ": " separators (S16).
const wantStagedSidecar = `{"name": "demo", "agents": ["claude", "cursor", "opencode"], "recipes": ["foo.bar"], "configured": []}` + "\n"

// TestInitWizardFullFlow pins S14's order and S16's outputs through one
// confirmed run: prompts in sequence on stdout, banner/preview/status on
// stderr, the staged manifest and sidecar byte for byte, the real manifest
// placed when missing, and the staging name family init.sh creates.
func TestInitWizardFullFlow(t *testing.T) {
	f := newWizardFixture(t)
	f.seedRecipe(t, "foo.bar", wizardRecipeBody("foo.bar", "1.2.3", "dotted recipe"))

	keys := wizardScript(
		enterText(),  // name: keep "demo"
		tui.KeyEnter, // topology: auto (detected)
		tui.KeyEnter, // agents: DEFAULT_AGENTS
		tui.KeySpace, // recipes: toggle foo.bar on
		tui.KeyEnter, // recipes: submit
		tui.KeyEnter, // confirm (default yes)
	)
	res, rc := runInitWizard(f.request(keys))
	if rc != 0 {
		t.Fatalf("exit = %d, want 0; stderr=%q", rc, f.stderr.String())
	}
	if res.Name != "demo" {
		t.Errorf("wizard name = %q, want %q", res.Name, "demo")
	}

	// S16: staged manifest byte for byte, under init.sh's staging name family.
	if !strings.HasPrefix(res.Staged, filepath.Join(f.tmp, "ai-specs-init-tui-")) || !strings.HasSuffix(res.Staged, ".toml") {
		t.Errorf("staged path = %q, want <TMPDIR>/ai-specs-init-tui-XXXXXX.toml", res.Staged)
	}
	staged := readFile(t, res.Staged)
	if staged != wantStagedManifest {
		t.Errorf("staged manifest differs from the Python's shape:\n--- got ---\n%s\n--- want ---\n%s", staged, wantStagedManifest)
	}

	// S16: the JSON sidecar at <out>.json.
	wantSidecar := strings.TrimSuffix(res.Staged, ".toml") + ".json"
	if res.Sidecar != wantSidecar {
		t.Errorf("sidecar path = %q, want %q", res.Sidecar, wantSidecar)
	}
	if got := readFile(t, res.Sidecar); got != wantStagedSidecar {
		t.Errorf("sidecar = %q, want %q", got, wantStagedSidecar)
	}

	// S16: the manifest ALSO lands at the real path when it does not exist yet.
	realPath := filepath.Join(f.target, "ai-specs", "ai-specs.toml")
	if got := readFile(t, realPath); got != wantStagedManifest {
		t.Errorf("real manifest = staged bytes? got:\n%s", got)
	}

	// S14: the prompt order is the spec's order, all on stdout.
	out := f.stdout.String()
	order := []string{
		"? Project name:",
		"Repo topology for worktree-flow:",
		"Select agents to enable:",
		"Select recipes to enable:",
		"Write ai-specs.toml with these choices?",
	}
	prev := -1
	for _, needle := range order {
		idx := strings.Index(out, needle)
		if idx < 0 {
			t.Errorf("stdout never drew %q:\n%s", needle, out)
			continue
		}
		if idx < prev {
			t.Errorf("stdout drew %q out of order:\n%s", needle, out)
		}
		prev = idx
	}
	// The topology choice offers the detected value first (S14).
	if !strings.Contains(out, "auto → standalone (detected)") {
		t.Errorf("stdout lacks the detected topology choice:\n%s", out)
	}

	// The wizard's own surfaces: banner + target on stderr, preview panel, and
	// the staged confirmation line.
	errOut := f.stderr.String()
	for _, needle := range []string{
		"│ ai-specs init",
		"Interactive project onboarding",
		"  target: " + f.target,
		"Preview",
		"name     demo",
		"recipes  foo.bar",
		"config   (defaults / later)",
		"mcp      configure later via ai-specs.toml",
		"✓ staged manifest → " + res.Staged,
	} {
		if !strings.Contains(errOut, needle) {
			t.Errorf("stderr lacks %q:\n%s", needle, errOut)
		}
	}
}

// TestInitWizardCancelWritesNothing pins S15 at every prompt: Ctrl-C, EOF and
// a declined confirm all end as exit 1 with the Cancelled line and no staged
// manifest, no sidecar, no project files and no staging temp.
func TestInitWizardCancelWritesNothing(t *testing.T) {
	cases := []struct {
		name string
		seed bool
		text []tui.TextKey
		keys []tui.Key
	}{
		{name: "name prompt EOF", text: nil},
		{name: "name prompt abort", text: []tui.TextKey{{Kind: tui.TextAbort}}},
		{name: "topology abort", text: enterText(), keys: []tui.Key{tui.KeyEscape}},
		{name: "agents abort", text: enterText(), keys: []tui.Key{tui.KeyEnter, tui.KeyEscape}},
		{name: "recipes abort", seed: true, text: enterText(),
			keys: []tui.Key{tui.KeyEnter, tui.KeyEnter, tui.KeyEscape}},
		{name: "confirm abort", text: enterText(),
			keys: []tui.Key{tui.KeyEnter, tui.KeyEnter, tui.KeyEscape}},
		{name: "confirm declined", text: enterText(),
			keys: []tui.Key{tui.KeyEnter, tui.KeyEnter, tui.KeyNo, tui.KeyEnter}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			f := newWizardFixture(t)
			if tc.seed {
				f.seedRecipe(t, "foo.bar", wizardRecipeBody("foo.bar", "1.2.3", "dotted recipe"))
			}
			res, rc := runInitWizard(f.request(wizardScript(tc.text, tc.keys...)))
			if rc != 1 {
				t.Fatalf("exit = %d, want 1 (cancel)", rc)
			}
			if res.Staged != "" || res.Sidecar != "" {
				t.Errorf("cancel returned staged paths: %+v", res)
			}
			if !strings.Contains(f.stderr.String(), "\nCancelled\n") {
				t.Errorf("stderr = %q, want the Cancelled line", f.stderr.String())
			}
			f.assertNoProjectWrites(t)
		})
	}
}

