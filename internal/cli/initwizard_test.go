// TestInitWizardCatalogScan pins the picker's inputs: sorted directory order,
// hidden and `test-` fixtures gone, a broken recipe.toml skipped WITH the
// notice, a directory without recipe.toml skipped silently, and the recipe
// titles carrying id, version and description.
func TestInitWizardCatalogScan(t *testing.T) {
	f := newWizardFixture(t)
	f.seedRecipe(t, "zzz-two", wizardRecipeBody("zzz-two", "1.2.3", "dotted recipe"))
	f.seedRecipe(t, "aaa-one", wizardRecipeBody("aaa-one", "9.9.9", "first recipe in sorted order"))
	f.seedRecipe(t, "broken-one", "this is not toml {{{\n")
	f.seedRecipe(t, "test-hidden", wizardRecipeBody("test-hidden", "1.0.0", "hidden"))
	if err := os.MkdirAll(filepath.Join(f.home, "catalog", "recipes", "dot-hidden"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(f.home, "catalog", "recipes", "norecipe"), 0o755); err != nil {
		t.Fatal(err)
	}

	// Enter through every prompt; nothing needs selecting for this pin.
	_, rc := runInitWizard(f.request(wizardScript(enterText(),
		tui.KeyEnter, tui.KeyEnter, tui.KeyEnter, tui.KeyEnter)))
	if rc != 0 {
		t.Fatalf("exit = %d, want 0; stderr=%q", rc, f.stderr.String())
	}
	out := f.stdout.String()
	first := strings.Index(out, "aaa-one  (9.9.9)")
	second := strings.Index(out, "zzz-two  (1.2.3)")
	if first < 0 || second < 0 {
		t.Fatalf("recipe titles missing from stdout:\n%s", out)
	}
	if first > second {
		t.Errorf("recipes are not in sorted order:\n%s", out)
	}
	if !strings.Contains(out, "first recipe in sorted order") {
		t.Errorf("the description is missing from the choice title:\n%s", out)
	}
	if !strings.Contains(f.stderr.String(), "  · skip catalog recipe broken-one:") {
		t.Errorf("the broken recipe was not skipped with a notice:\n%s", f.stderr.String())
	}
	for _, hidden := range []string{"test-hidden", "dot-hidden", "norecipe"} {
		if strings.Contains(out, hidden) {
			t.Errorf("%q was offered in the picker:\n%s", hidden, out)
		}
	}
	if strings.Contains(f.stderr.String(), "skip catalog recipe norecipe") {
		t.Errorf("a directory without recipe.toml must be skipped silently:\n%s", f.stderr.String())
	}
}

