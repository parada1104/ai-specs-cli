// initWizardRequest is everything the wizard reads and writes: the resolved
// target, the name prefill (init.sh passes the basename), the CLI home for
// the catalog, and the three streams. OpenKeys produces the keystrokes — the
// production seam opens a raw-mode terminal, a test scripts one. DepGate is
// the CLI-dep gate seam (S37); nil selects the production runner that spawns
// the legacy script over the same TTY.
type initWizardRequest struct {
	Target   string
	Name     string
	Home     string
	Stdin    io.Reader
	Stdout   io.Writer
	Stderr   io.Writer
	OpenKeys initWizardOpener
	DepGate  wizardDepGate
}

// wizardDepGate runs the CLI-dep gate for one selected recipe (S37).
// config_wizard._dep_gate — check_cli_deps' panel, dep_install's TTY offer and
// the "Configure anyway?" confirm — has no native side, so init keeps that leg
// on the legacy script for recipes declaring [[deps.cli]] instead of
// half-porting it or silently skipping them. U6e kept the same decision on its
// own route, so the native dep gate is U7's; this seam retires when that lands.
type wizardDepGate func(recipeID string) wizardDepGateOutcome

// wizardDepGateOutcome is how one gate run answered:
//
//	Proceed — configure the recipe;
//	Skip    — declined: print the legacy `Skipped <id> (missing CLI deps)` line and go on;
//	neither — the child already printed its own line (its read failure): continue quietly;
//	Rc      — non-zero aborts the wizard with that code (Err, when set, is
//	          worded through init_tui.py's `ERROR: interactive init failed`).
type wizardDepGateOutcome struct {
	Proceed bool
	Skip    bool
	Rc      int
	Err     error
}

// initWizardResult is what a confirmed wizard hands back to the verb: the
// project name it settled on (init.sh adopts it from the JSON sidecar) and
// the staged manifest it wrote, for the manifest step to install.
type initWizardResult struct {
	Name    string
	Staged  string
	Sidecar string
}

// initWizardOpener yields the wizard's key source over the given streams plus
// a closer that restores the terminal, or a non-zero rc meaning "the TUI is
// unavailable" before any prompt is drawn (S15's exit 3).
type initWizardOpener func(stdin io.Reader, stdout io.Writer) (tui.KeySource, func(), int)

// openInitWizardKeys is the production opener: init_tui.py's own guard
// (`if not sys.stdin.isatty() or not sys.stdout.isatty(): return 3`) plus the
// raw-mode takeover. Every refusal is silent — the verb prints the fallback
// line, as init.sh does.
func openInitWizardKeys(stdin io.Reader, stdout io.Writer) (tui.KeySource, func(), int) {
	if !isTTY(stdin, stdout) {
		return nil, nil, 3
	}
	file, ok := stdin.(*os.File)
	if !ok {
		return nil, nil, 3
	}
	term, err := tui.NewTerminal(file)
	if err != nil {
		return nil, nil, 3
	}
	return term, term.Close, 0
}

// runInitWizard is init_tui.run_wizard. See the exit-code contract at the top
// of this file; rc 1 is a cancel that wrote NOTHING (S15), rc 3 leaves the
// classic path in charge.
func runInitWizard(req initWizardRequest) (res initWizardResult, rc int) {
	if req.OpenKeys == nil {
		return initWizardResult{}, 3
	}
	keys, closeKeys, rc := req.OpenKeys(req.Stdin, req.Stdout)
	if rc != 0 {
		return initWizardResult{}, rc
	}
	if closeKeys != nil {
		defer closeKeys()
	}
	// init.sh removes the staging set on rc 1/3 (its EXIT trap is the belt
	// for earlier exits). From here on, any failure takes the staged files
	// back out with it, so a failed wizard also writes NOTHING (S15).
	var staging []string
	defer func() {
		if rc != 0 {
			for _, path := range staging {
				os.Remove(path)
			}
		}
	}()

	// init_tui.py's main-level handler: an unexpected failure must never be
	// mistaken for a cancel, so it reports and returns 3 — the shell's rc-3
	// branch then falls back to classic.
	fail := func(err error) (initWizardResult, int) {
		fmt.Fprintf(req.Stderr, "ERROR: interactive init failed: %v\n", err)
		return initWizardResult{}, 3
	}
	cancel := func() (initWizardResult, int) {
		fmt.Fprintln(req.Stderr)
		fmt.Fprintln(req.Stderr, "Cancelled")
		return initWizardResult{}, 1
	}

	// Banner: blank line, the panel, the target line, a blank line (S14).
	fmt.Fprintln(req.Stderr)
	fmt.Fprint(req.Stderr, renderWizardPanel("", []string{"ai-specs init", "Interactive project onboarding"}))
	fmt.Fprintf(req.Stderr, "  target: %s\n", req.Target)
	fmt.Fprintln(req.Stderr)

	// 1. Project name — the text prompt with a default (S13/S14).
	prefill := req.Name
	if prefill == "" {
		prefill = filepath.Base(req.Target)
	}
	projectName, ok := tui.Text(req.Stdout, keys, "Project name:", prefill)
	if !ok {
		return cancel()
	}

	// 1b. Repo topology — the detected value offered first, then the three
	// literals. The detection call is init_tui.py's
	// `resolve_repo_topology(target, "auto")` through the SAME resolver the
	// rest of the CLI uses (target.ProjectRepoTopology); the empty manifest
	// table pins configured="auto" so detection never reads a manifest, just
	// as the Python passes "auto" literally.
	detected := target.ProjectRepoTopology(req.Target, &toml.Table{})
	topology, ok := tui.Select(req.Stdout, keys, "Repo topology for worktree-flow:", []tui.Choice{
		{Title: fmt.Sprintf("auto → %s (detected)", detected.Resolved), Value: "auto"},
		{Title: "standalone", Value: "standalone"},
		{Title: "monorepo-apps", Value: "monorepo-apps"},
		{Title: "monorepo-submodules", Value: "monorepo-submodules"},
	})
	if !ok {
		return cancel()
	}

	// 2. Agents — the blank line console.print() draws before the checkbox.
	fmt.Fprintln(req.Stderr)
	agentChoices := make([]tui.Choice, len(initWizardAgents))
	agentChecked := make([]bool, len(initWizardAgents))
	for i, agent := range initWizardAgents {
		agentChoices[i] = tui.Choice{Title: agent, Value: agent}
		agentChecked[i] = slices.Contains(initWizardDefaultAgents, agent)
	}
	agents, ok := tui.MultiSelect(req.Stdout, keys, "Select agents to enable:", agentChoices, agentChecked)
	if !ok {
		return cancel()
	}

	// 3. Recipes — the catalog picker, skipped entirely when the catalog is
	// empty (S14).
	catalog, err := wizardCatalog(req.Home, req.Stderr)
	if err != nil {
		return fail(err)
	}
	var recipes []string
	if len(catalog) > 0 {
		recipeChoices := make([]tui.Choice, len(catalog))
		recipeChecked := make([]bool, len(catalog))
		for i, entry := range catalog {
			recipeChoices[i] = tui.Choice{
				Title: fmt.Sprintf("%s  (%s) — %s", entry.ID, entry.Version, runeTruncate(entry.Description, 64)),
				Value: entry.ID,
			}
			recipeChecked[i] = slices.Contains(initWizardDefaultRecipes, entry.ID)
		}
		recipes, ok = tui.MultiSelect(req.Stdout, keys, "Select recipes to enable:", recipeChoices, recipeChecked)
		if !ok {
			return cancel()
		}
	}

	// 3.5 Configure selected recipes — U4b-2: init_tui.py:204-233's
	// _configure_recipes in its exact order (read → CLI-dep gate → fields
	// check → per-recipe confirm → wizard), collecting answers for the render
	// below where S19 used to print a deferral line.
	configured := map[string]map[string]any{}
	depGate := req.DepGate
	if depGate == nil {
		depGate = func(rid string) wizardDepGateOutcome {
			return runLegacyInitDepGate(req, keys, rid, recipe.CatalogDir(req.Home))
		}
	}
	for _, rid := range recipes {
		// Legacy read_recipe(<catalog>, id): a failure is Python's
		// `skip config for <rid>: <exc>` on the rich console (stderr), then on
		// to the next recipe. The path joins the id verbatim like Path does.
		loaded, err := schema.LoadRecipeToml(filepath.Join(recipe.CatalogDir(req.Home), rid, "recipe.toml"))
		if err != nil {
			fmt.Fprintf(req.Stderr, "skip config for %s: %v\n", rid, err)
			continue
		}
		// The gate fires BEFORE the fields check — _configure_recipes' order,
		// even for a recipe that declares no config at all (S37).
		if len(loaded.CliDeps) > 0 {
			outcome := depGate(rid)
			if outcome.Err != nil {
				return fail(outcome.Err)
			}
			if outcome.Rc != 0 {
				return initWizardResult{}, outcome.Rc
			}
			if outcome.Skip {
				fmt.Fprintf(req.Stderr, "Skipped %s (missing CLI deps)\n", rid)
				continue
			}
			if !outcome.Proceed {
				// The child already printed its own line (its read failure).
				continue
			}
		}
		// The fields check reads the RAW schema, exactly like the Python
		// (`if not recipe.config_schema.fields`): a recipe whose only field is
		// repo_topology still gets the confirm, then the filtered schema below
		// prompts nothing (S35).
		if loaded.ConfigSchema == nil || len(loaded.ConfigSchema.Fields) == 0 {
			continue
		}
		doNow, ok := tui.Confirm(req.Stdout, keys, "Configure "+rid+" now?", true)
		if !ok {
			// `do_now is None` → KeyboardInterrupt → Cancelled, exit 1 (S15).
			return cancel()
		}
		if !doNow {
			continue
		}
		// existing_config is init_tui's literal `{}`: the wizard only runs when
		// no manifest exists yet (the shell's skip branch, S16/S4), so the
		// existing-wins step has nothing to read on this route.
		values, ok, werr := runConfigWizard(loaded.ID, wizardPromptSchema(loaded.ConfigSchema), map[string]any{},
			tuiWizardPrompts{out: req.Stdout, keys: keys})
		if werr != nil {
			// Python's re.error escaping run_config_wizard reaches init_tui
			// main's failure arm: `ERROR: interactive init failed: …`, exit 3.
			return fail(werr)
		}
		if !ok || len(values) == 0 {
			// A cancelled field prompt is Python's `return {}`: that recipe
			// stays unconfigured and the loop CONTINUES (recorded EOF
			// divergence in the unit document: legacy Ctrl-D surfaces
			// EOFError and cancels the whole wizard instead).
			continue
		}
		// init_tui.py's project-owned promotion (:266-270): the schema filter
		// keeps repo_topology out of every prompt (S18), so nothing can reach
		// this branch through the prompts — it mirrors the Python's post-loop
		// pop for the values map all the same.
		if promoted, has := values[initWizardProjectOwnedConfigKey]; has {
			delete(values, initWizardProjectOwnedConfigKey)
			if s, isStr := promoted.(string); isStr && s != "" {
				topology = s
			}
		}
		configured[rid] = values
	}

	// 4. Preview panel + confirm (S14). The config row is sorted(configured)
	// when anything was configured, the deferred summary otherwise (S38).
	configuredIDs := make([]string, 0, len(configured))
	for id := range configured {
		configuredIDs = append(configuredIDs, id)
	}
	sort.Strings(configuredIDs)
	configSummary := "(defaults / later)"
	if len(configuredIDs) > 0 {
		configSummary = strings.Join(configuredIDs, ", ")
	}
	fmt.Fprintln(req.Stderr)
	fmt.Fprint(req.Stderr, renderWizardPanel("Preview", []string{
		"name     " + projectName,
		"agents   " + wizardJoinOrNone(agents, "(none)"),
		"recipes  " + wizardJoinOrNone(recipes, "(none)"),
		"config   " + configSummary,
		"mcp      configure later via ai-specs.toml",
	}))
	confirmed, ok := tui.Confirm(req.Stdout, keys, "Write ai-specs.toml with these choices?", true)
	if !ok || !confirmed {
		return cancel()
	}

	// Outputs (S16): staged manifest — configured values rendered exactly as
	// _render_manifest writes them (S36) —, the real manifest when it does not
	// exist yet, the JSON sidecar with its configured list, then the
	// confirmation line — that order.
	manifest, err := renderWizardManifest(projectName, agents, recipes, configured, topology)
	if err != nil {
		return fail(err)
	}
	base, err := os.CreateTemp("", "ai-specs-init-tui-XXXXXX")
	if err != nil {
		return fail(err)
	}
	base.Close()
	staged := base.Name() + ".toml"
	sidecar := base.Name() + ".json"
	staging = []string{base.Name(), staged, sidecar}
	if err := os.WriteFile(staged, []byte(manifest), 0o644); err != nil {
		return fail(err)
	}
	// init_tui.py places the confirmed manifest at the real path now (the
	// comment there: harness-env collection reads enabled recipes from it) —
	// only when nothing is there yet; an existing file is the user's (S16/S4).
	realPath := filepath.Join(req.Target, "ai-specs", "ai-specs.toml")
	if fi, statErr := os.Stat(realPath); statErr != nil || !fi.Mode().IsRegular() {
		if err := os.MkdirAll(filepath.Dir(realPath), 0o755); err != nil {
			return fail(err)
		}
		if err := os.WriteFile(realPath, []byte(manifest), 0o644); err != nil {
			return fail(err)
		}
	}
	if err := os.WriteFile(sidecar, []byte(renderWizardSidecar(projectName, agents, recipes, configuredIDs)), 0o644); err != nil {
		return fail(err)
	}
	fmt.Fprintf(req.Stderr, "✓ staged manifest → %s\n", staged)

	// S28 (init_tui.py:390-391): prompt for MCP env vars → ai-specs.env +
	// root .envrc + direnv allow, when the manifest's enabled recipes collect
	// anything. The Python wraps both calls in try/except: pass — and every
	// branch inside OfferHarnessEnv soft-fails with the Python's own line — so
	// a declined or cancelled offer (S30) ends the OFFER only: the staged
	// manifest stays, the wizard returns 0 and the verb's classic continuation
	// runs exactly as it does today.
	if len(sync.CollectEnvVars(req.Target, req.Home)) > 0 {
		sync.OfferHarnessEnv(req.Target, req.Home,
			&wizardEnvPrompts{out: req.Stdout, keys: keys}, req.Stdout, req.Stderr)
	}
	return initWizardResult{Name: projectName, Staged: staged, Sidecar: sidecar}, 0
}

// wizardEnvPrompts is internal/cli's half of sync.EnvOfferPrompts (S29): the
// offer's questions on internal/tui over the wizard's own key source and
// stdout — questionary's stream — while the wizard's rich console stays on
// stderr (S20). questionary's None (Ctrl-C, EOF, a declined yes/no) answers
// sync.ErrEnvOfferCancelled, which OfferHarnessEnv swallows as "cancelled".
type wizardEnvPrompts struct {
	out  io.Writer
	keys tui.KeySource
}

var _ sync.EnvOfferPrompts = (*wizardEnvPrompts)(nil)

func (p *wizardEnvPrompts) Confirm(message string, def bool) (bool, error) {
	answer, ok := tui.Confirm(p.out, p.keys, message, def)
	if !ok {
		return false, sync.ErrEnvOfferCancelled
	}
	return answer, nil
}

func (p *wizardEnvPrompts) Select(message string, choices []string, initial string) (string, error) {
	tuiChoices := make([]tui.Choice, len(choices))
	for i, choice := range choices {
		tuiChoices[i] = tui.Choice{Title: choice, Value: choice}
	}
	answer, ok := tui.SelectDefault(p.out, p.keys, message, tuiChoices, initial)
	if !ok {
		return "", sync.ErrEnvOfferCancelled
	}
	return answer, nil
}

func (p *wizardEnvPrompts) Password(message, instruction string) (string, error) {
	answer, ok := tui.Password(p.out, p.keys, message, instruction)
	if !ok {
		return "", sync.ErrEnvOfferCancelled
	}
	return answer, nil
}

func (p *wizardEnvPrompts) Text(message, defaultValue string) (string, error) {
	// TextRAW: questionary.text does not trim (S30's correction); the blank
	// rule that protects a secret is write_env's own.
	answer, ok := tui.TextRaw(p.out, p.keys, message, defaultValue)
	if !ok {
		return "", sync.ErrEnvOfferCancelled
	}
	return answer, nil
}

// cleanupInitStaging removes the wizard's staging set — the base temp, the
// staged manifest and its JSON sidecar — mirroring init.sh's
// `rm -f "$TUI_TOML" "${TUI_TOML%.toml}.json" "${TUI_TOML%.*}"` after the
// manifest step installs it.
func cleanupInitStaging(staged string) {
	if staged == "" {
		return
	}
	base := strings.TrimSuffix(staged, ".toml")
	for _, path := range []string{staged, base + ".json", base} {
		os.Remove(path)
	}
}

// initWizardRecipe is one catalog entry as the picker labels it.
type initWizardRecipe struct {
	ID          string
	Dir         string
	Version     string
	Description string
}

// wizardCatalog is init_tui._catalog_recipes: the sorted directory listing of
// <home>/catalog/recipes with the hidden and `test-` fixture directories
// skipped, each recipe read for id/version/description with the same
// fallbacks (directory name, "0.0.0", ""). An unreadable recipe.toml is
// skipped WITH the notice the Python prints; a directory without one is
// skipped silently. The location itself comes from recipe.CatalogDir, the one
// resolver the CLI owns — this scan exists beside recipe.List because the
// wizard needs the description and a skip (not an error status), which is the
// same duplication init_tui.py has next to recipe-list.py.
func wizardCatalog(home string, notice io.Writer) ([]initWizardRecipe, error) {
	dir := recipe.CatalogDir(home)
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		// init_tui.py's iterdir failure propagates to main → rc 3.
		return nil, err
	}
	var out []initWizardRecipe
	for _, de := range entries {
		name := de.Name()
		if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "test-") {
			continue
		}
		// is_dir() follows symlinks, so a symlinked recipe counts.
		info, err := os.Stat(filepath.Join(dir, name))
		if err != nil || !info.IsDir() {
			continue
		}
		path := filepath.Join(dir, name, "recipe.toml")
		fi, err := os.Stat(path)
		if err != nil || fi.IsDir() {
			continue
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			fmt.Fprintf(notice, "  · skip catalog recipe %s: %v\n", name, err)
			continue
		}
		data, err := toml.Parse(raw)
		if err != nil {
			fmt.Fprintf(notice, "  · skip catalog recipe %s: %v\n", name, err)
			continue
		}
		meta, _ := data.Table("recipe")
		id := strings.TrimSpace(wizardMetaString(meta, "id", name))
		if id == "" {
			fmt.Fprintf(notice, "  · skip catalog recipe %s: empty recipe id in %s\n", name, path)
			continue
		}
		out = append(out, initWizardRecipe{
			ID:          id,
			Dir:         name,
			Version:     wizardMetaString(meta, "version", "0.0.0"),
			Description: wizardMetaString(meta, "description", ""),
		})
	}
	return out, nil
}

// wizardMetaString is init_tui.py's `str(meta.get(key) or fallback)`: absent
// or falsy falls back to the second argument (or the directory name and the
// "0.0.0"/"" defaults the Python hard-codes).
func wizardMetaString(meta *toml.Table, key, fallback string) string {
	if meta == nil {
		return fallback
	}
	v, ok := meta.Get(key)
	if !ok || v == nil {
		return fallback
	}
	switch t := v.(type) {
	case string:
		if t == "" {
			return fallback
		}
		return t
	case bool:
		if !t {
			return fallback
		}
		return "True"
	case int64:
		if t == 0 {
			return fallback
		}
		return strconv.FormatInt(t, 10)
	case float64:
		if t == 0 {
			return fallback
		}
		return strconv.FormatFloat(t, 'g', -1, 64)
	default:
		return fmt.Sprintf("%v", v)
	}
}

// wizardPromptSchema is init_tui._wizard_recipe: the schema WITHOUT the
// project-owned keys, so runConfigWizard can never prompt for repo_topology
// (S18). Everything else — Extra, Tables, the surviving fields — passes
// through untouched, exactly like the Python's dataclasses.replace.
func wizardPromptSchema(cs *schema.ConfigSchema) *schema.ConfigSchema {
	if cs == nil {
		return nil
	}
	promptable := make(map[string]*schema.ConfigField, len(cs.Fields))
	for key, field := range cs.Fields {
		if key != initWizardProjectOwnedConfigKey {
			promptable[key] = field
		}
	}
	if len(promptable) == len(cs.Fields) {
		return cs
	}
	return &schema.ConfigSchema{Fields: promptable, Extra: cs.Extra, Tables: cs.Tables}
}

// The dep-gate seam's own exit codes (S37): the language with the legacy
// driver. 0/10/11/3 are the driver's; ANY other code is a crash — Python's
// traceback already went to stderr, and the wizard words it through
// init_tui main's failure arm instead of mistaking it for a decline.
const (
	initDepGatePass      = 0
	initDepGateDeclined  = 10
	initDepGateReadError = 11
	initDepGateNoTUI     = 3
)

// initDepGateDriver is the seam's Python side, run as `python3 -c` against the
// wizard's own install root. It loads init_tui.py at module level only (main
// is guarded), runs the SAME vendor bootstrap the legacy wizard runs before
// its first prompt (_ensure_deps — its offer lines land on the wizard's TTY,
// late rather than at start: recorded in the unit document), reads the recipe
// through recipe-read, and hands it to config_wizard._dep_gate — panel,
// dep_install TTY offer and the "Configure anyway?" confirm all the legacy
// script's own bytes. Exit codes: 0 configure, 10 declined, 11 read failed
// (its `skip config for …` line already printed), 3 _ensure_deps' own rc.
const initDepGateDriver = `import runpy, sys
from pathlib import Path
home = Path(sys.argv[1])
recipe_id = sys.argv[2]
catalog = Path(sys.argv[3])
wizard = runpy.run_path(str(home / "lib" / "_internal" / "init_tui.py"), run_name="ai_specs_init_dep_gate")
rc = wizard["_ensure_deps"]()
if rc is not None:
    sys.exit(rc)
try:
    recipe = wizard["_load_sibling"]("recipe-read").read_recipe(catalog, recipe_id)
except Exception as exc:
    print(f"skip config for {recipe_id}: {exc}", file=sys.stderr)
    sys.exit(11)
from rich.console import Console
ok = wizard["_load_sibling"]("config_wizard")._dep_gate(recipe, Console(stderr=True))
sys.exit(0 if ok else 10)`

// runLegacyInitDepGate is S37's seam, the hub delegate's tactic applied to one
// wizard step: raw mode is SUSPENDED around the child (internal/tui's
// Terminal documents exactly this use), the child inherits the wizard's own
// TTY streams so questionary prompts on the same terminal the Go prompts do,
// and raw mode resumes before the next prompt. AI_SPECS_HOME is pinned to the
// wizard's home through childEnv — the env builder shim.go already owns —
// because the driver's _ensure_deps and _dep_gate resolve the install root
// from it. A non-terminal stream answers the wizard's rc 3: the seam never
// runs over pipes, where questionary could neither draw nor read.
func runLegacyInitDepGate(req initWizardRequest, keys tui.KeySource, recipeID, catalogDir string) wizardDepGateOutcome {
	failWith := func(err error) wizardDepGateOutcome {
		return wizardDepGateOutcome{Rc: 3, Err: err}
	}
	stdin, ok := req.Stdin.(*os.File)
	if !ok {
		return failWith(fmt.Errorf("the CLI-dep gate for %s needs a terminal stdin", recipeID))
	}
	stdout, ok := req.Stdout.(*os.File)
	if !ok {
		return failWith(fmt.Errorf("the CLI-dep gate for %s needs a terminal stdout", recipeID))
	}
	term, _ := keys.(interface {
		Suspend()
		Resume() error
	})
	if term != nil {
		term.Suspend()
	}
	cmd := exec.Command("python3", "-c", initDepGateDriver, req.Home, recipeID, catalogDir)
	cmd.Stdin = stdin
	cmd.Stdout = stdout
	cmd.Stderr = req.Stderr
	cmd.Env = childEnv(req.Home, "", "")
	runErr := cmd.Run()
	if term != nil {
		if resumeErr := term.Resume(); resumeErr != nil {
			return failWith(resumeErr)
		}
	}
	code := 0
	if runErr != nil {
		var exitErr *exec.ExitError
		if !errors.As(runErr, &exitErr) {
			return failWith(fmt.Errorf("the CLI-dep gate for %s did not start: %v", recipeID, runErr))
		}
		if code = exitErr.ExitCode(); code < 0 {
			return failWith(fmt.Errorf("the CLI-dep gate for %s was killed before exiting", recipeID))
		}
	}
	switch code {
	case initDepGatePass:
		return wizardDepGateOutcome{Proceed: true}
	case initDepGateDeclined:
		return wizardDepGateOutcome{Skip: true}
	case initDepGateReadError:
		return wizardDepGateOutcome{} // the driver printed `skip config for …`
	case initDepGateNoTUI:
		// _ensure_deps' own answer (vendor missing and declined): the legacy
		// wizard returns 3 for it too and init.sh's rc-3 branch takes over,
		// with no message of its own.
		return wizardDepGateOutcome{Rc: 3}
	default:
		return failWith(fmt.Errorf("the CLI-dep gate for %s exited %d", recipeID, code))
	}
}

// renderWizardManifest is init_tui._render_manifest (S16): header, [project]
// with name/subrepos/repo_topology, [agents], one enabled table per selected
// recipe with its config table when values exist, and the trailing comment
// pair. configured is _configure_recipes' collected map (U4b-2): keys sorted,
// project-owned keys never landing under a recipe (S16/S18), values through
// toml_write's renderer — the staged bytes the Python's own render produces
// (S36), which is why this route does NOT write the config through
// config.UpdateRecipeConfig: that surgery appends at the recipe region's END,
// after the trailing comments for the last recipe, and would break the byte
// order S16 pins.
func renderWizardManifest(name string, agents, recipeIDs []string, configured map[string]map[string]any, topology string) (string, error) {
	lines := []string{
		initWizardHeader,
		"",
		"[project]",
		"name = " + wizardTOMLQuote(name),
		"subrepos = []",
		"repo_topology = " + wizardTOMLQuote(topology),
		"",
		"[agents]",
		"enabled = " + wizardTOMLList(agents),
		"",
	}
	if len(recipeIDs) > 0 {
		lines = append(lines, "# Recipes — named bundles from catalog/recipes/<id>/")
		for _, id := range recipeIDs {
			lines = append(lines, "[recipes."+wizardTOMLKey(id)+"]", "enabled = true")
			vals := configured[id]
			keys := make([]string, 0, len(vals))
			for key := range vals {
				if key != initWizardProjectOwnedConfigKey {
					keys = append(keys, key)
				}
			}
			sort.Strings(keys)
			if len(keys) > 0 {
				lines = append(lines, "", "[recipes."+wizardTOMLKey(id)+".config]")
				for _, key := range keys {
					value, err := wizardTOMLValue(vals[key])
					if err != nil {
						return "", err
					}
					lines = append(lines, wizardTOMLKey(key)+" = "+value)
				}
			}
			lines = append(lines, "")
		}
	}
	lines = append(lines,
		"# [[deps]] — add with: ai-specs skills add <url>",
		"# [mcp.*]  — optional MCP servers; distributed by sync-agent",
		"")
	return strings.Join(lines, "\n"), nil
}

// renderWizardSidecar is `json.dumps(meta) + "\n"` with Python's insertion
// order and separators — name, agents, recipes, configured (S16).
// configuredIDs is sorted(configured): the ids the wizard actually got values
// for (S38). init.sh reads it back with json.load and adopts the name; the
// wizard returns the same value directly, and the bytes stay the Python's for
// anything that compares them.
func renderWizardSidecar(name string, agents, recipeIDs, configuredIDs []string) string {
	list := func(ids []string) string {
		parts := make([]string, len(ids))
		for i, id := range ids {
			parts[i] = pythonJSONString(id)
		}
		return "[" + strings.Join(parts, ", ") + "]"
	}
	return "{" +
		`"name": ` + pythonJSONString(name) + ", " +
		`"agents": ` + list(agents) + ", " +
		`"recipes": ` + list(recipeIDs) + ", " +
		`"configured": ` + list(configuredIDs) + "}" + "\n"
}

// renderWizardPanel is rich's Panel.fit over plain rows: rounded box, rows
// padded to the widest one, a centred title row when there is a title (the
// odd dash goes right, which is where rich's centre lands). The exact bytes
// are pinned against rich's own output in TestWizardPanelsMatchRichPins.
func renderWizardPanel(title string, rows []string) string {
	width := 0
	for _, row := range rows {
		if n := utf8.RuneCountInString(row); n > width {
			width = n
		}
	}
	inner := width + 2 // panel padding is one cell on each side
	var b strings.Builder
	if title == "" {
		b.WriteString("╭" + strings.Repeat("─", inner) + "╮\n")
	} else {
		dashes := inner - (utf8.RuneCountInString(title) + 2)
		left := dashes / 2
		b.WriteString("╭" + strings.Repeat("─", left) + " " + title + " " +
			strings.Repeat("─", dashes-left) + "╮\n")
	}
	for _, row := range rows {
		b.WriteString("│ " + row + strings.Repeat(" ", width-utf8.RuneCountInString(row)) + " │\n")
	}
	b.WriteString("╰" + strings.Repeat("─", inner) + "╯\n")
	return b.String()
}

// wizardJoinOrNone is the preview's `', '.join(items) if items else fallback`.
func wizardJoinOrNone(items []string, fallback string) string {
	if len(items) == 0 {
		return fallback
	}
	return strings.Join(items, ", ")
}

// runeTruncate is Python's `s[:64]` — a slice of CODE POINTS, not bytes,
// which is what the recipe choice title's description cut does.
func runeTruncate(s string, n int) string {
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	runes := []rune(s)
	return string(runes[:n])
}

// wizardTOMLKey is init_tui._toml_key (S17): bare when it matches
// ^[A-Za-z0-9_-]+$ , quoted as a JSON-style basic string otherwise — so
// foo.bar renders as [recipes."foo.bar"].
func wizardTOMLKey(key string) string {
	bare := key != ""
	for _, r := range key {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' ||
			r >= '0' && r <= '9' || r == '_' || r == '-') {
			bare = false
			break
		}
	}
	if bare {
		return key
	}
	return wizardTOMLQuote(key)
}

// wizardTOMLValue is toml_write.toml_value for the types the wizard writes.
// Anything else is an error, which runInitWizard reports through the
// unexpected-failure branch (rc 3), same as Python's TypeError.
func wizardTOMLValue(v any) (string, error) {
	switch t := v.(type) {
	case string:
		return wizardTOMLQuote(t), nil
	case bool:
		if t {
			return "true", nil
		}
		return "false", nil
	case int:
		return strconv.Itoa(t), nil
	case int64:
		return strconv.FormatInt(t, 10), nil
	case float64:
		return strconv.FormatFloat(t, 'g', -1, 64), nil
	case []string:
		return wizardTOMLList(t), nil
	case []any:
		parts := make([]string, len(t))
		for i, item := range t {
			s, err := wizardTOMLValue(item)
			if err != nil {
				return "", err
			}
			parts[i] = s
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	default:
		return "", fmt.Errorf("cannot serialize %T as a TOML value", v)
	}
}

// wizardTOMLList is toml_value for a string list: a JSON-style array literal.
func wizardTOMLList(items []string) string {
	parts := make([]string, len(items))
	for i, item := range items {
		parts[i] = wizardTOMLQuote(item)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// wizardTOMLQuote writes s as a TOML basic string through json.dumps' escapes
// (tw.toml_value quotes strings with json.dumps), so the staged bytes keep
// the Python's shape (S16): control characters get the short escapes or
// \uXXXX (lowercase, as json writes it), non-ASCII BMP runes are escaped too.
// Two deliberate deviations from json.dumps, both because the result must be
// a manifest that PARSES — init never overwrites it (S4): astral runes stay
// raw instead of becoming surrogate halves (which TOML forbids), and DEL
// (U+007F, which TOML also forbids and json leaves raw) is escaped.
func wizardTOMLQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\b':
			b.WriteString(`\b`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\f':
			b.WriteString(`\f`)
		case '\r':
			b.WriteString(`\r`)
		default:
			switch {
			case r < 0x20:
				fmt.Fprintf(&b, `\u%04x`, r)
			case r == 0x7f:
				b.WriteString(`\u007f`)
			case r > 0x7e && r <= 0xffff:
				fmt.Fprintf(&b, `\u%04x`, r)
			default:
				// Printable ASCII stays printable; astral runes stay raw.
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// pythonJSONString is json.dumps for one string: the same short escapes and
// control \uXXXX, but ensure_ascii's full escaping — non-ASCII BMP as \uXXXX
// and astral runes as the surrogate pair json.dumps emits (legal JSON, and
// Go's decoder recombines the pair when anything reads the sidecar back).
func pythonJSONString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\b':
			b.WriteString(`\b`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\f':
			b.WriteString(`\f`)
		case '\r':
			b.WriteString(`\r`)
		default:
			switch {
			case r < 0x20:
				fmt.Fprintf(&b, `\u%04x`, r)
			case r <= 0x7f:
				b.WriteRune(r)
			case r <= 0xffff:
				fmt.Fprintf(&b, `\u%04x`, r)
			default:
				u := r - 0x10000
				fmt.Fprintf(&b, `\u%04x\u%04x`, 0xd800+(u>>10), 0xdc00+(u&0x3ff))
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
